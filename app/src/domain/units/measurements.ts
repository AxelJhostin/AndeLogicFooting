/** Conversiones explícitas para valores canónicos SI. No aplica criterios normativos. */
export const kilonewtonsToNewtons = (valueInKilonewtons: number) => valueInKilonewtons * 1_000

export const kilopascalsToPascals = (valueInKilopascals: number) => valueInKilopascals * 1_000

export const metersToMillimeters = (valueInMeters: number) => valueInMeters * 1_000
